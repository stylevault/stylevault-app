// Generates db/seed.sql from src/data so reference data has one source of truth.
// Run `npm run db:seed` (local) or `npm run db:seed:remote` after editing countries, topics or sources.
// Re-running is safe: rows are upserted, and source health columns are left untouched.
import { writeFileSync } from 'node:fs';
import { COUNTRIES, slugify } from '../src/data/countries.js';
import { COUNTRY_FACTS } from '../src/data/country-facts.js';
import { TOPICS } from '../src/data/topics.js';
import { SOURCES } from '../src/data/sources.js';

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const lines = ['-- Generated by scripts/build-seed.mjs. Do not edit by hand.', ''];

for (const c of COUNTRIES) {
  const f = COUNTRY_FACTS[c.code];
  if (!f) throw new Error(`Missing country facts for ${c.code}`);
  lines.push(
    `INSERT INTO countries (code, name, slug, region, capital, iso3, languages, currency, blocs) VALUES (${[
      c.code, c.name, slugify(c.name), c.region, c.capital, f.iso3, f.languages, f.currency, JSON.stringify(f.blocs),
    ].map(q).join(', ')})` +
    ' ON CONFLICT(code) DO UPDATE SET name = excluded.name, slug = excluded.slug, region = excluded.region, capital = excluded.capital,' +
    ' iso3 = excluded.iso3, languages = excluded.languages, currency = excluded.currency, blocs = excluded.blocs;',
  );
}
lines.push('');

TOPICS.forEach((t, i) => {
  lines.push(
    `INSERT INTO topics (slug, name, color, sort) VALUES (${q(t.slug)}, ${q(t.name)}, ${q(t.color)}, ${i})` +
    ` ON CONFLICT(slug) DO UPDATE SET name = excluded.name, color = excluded.color, sort = excluded.sort;`,
  );
});
lines.push('');

// New sources are due immediately; next_check_at = list position spreads the first checks
// across consecutive cron runs in a stable order.
SOURCES.forEach((s, i) => {
  lines.push(
    `INSERT INTO sources (slug, name, homepage, feed_url, country_code, language, kind, scope, next_check_at) VALUES (${[
      s.slug, s.name, s.homepage, s.feed, s.country, s.lang, s.kind || 'news', s.scope || 'africa',
    ].map(q).join(', ')}, ${i})` +
    ' ON CONFLICT(slug) DO UPDATE SET name = excluded.name, homepage = excluded.homepage, feed_url = excluded.feed_url,' +
    ' country_code = excluded.country_code, language = excluded.language, kind = excluded.kind, scope = excluded.scope;',
  );
});

const out = new URL('../db/seed.sql', import.meta.url);
writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${COUNTRIES.length} countries, ${TOPICS.length} topics, ${SOURCES.length} sources → db/seed.sql`);
